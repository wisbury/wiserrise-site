/** "2026-11-06" → "6 Kasım 2026" / "6 November 2026" / "6. November 2026" */
export function formatDate(locale: Locale, iso: string): string {
  const d = Number(iso.slice(8, 10)), m = v2ui[locale].months[Number(iso.slice(5, 7)) - 1], y = iso.slice(0, 4);
  return locale === 'de' ? `${d}. ${m} ${y}` : `${d} ${m} ${y}`;
}
